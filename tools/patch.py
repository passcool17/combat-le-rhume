"""Rebuild the GitHub Pages copy from the original Grok Build client bundle.
Usage: python3 tools/patch.py <orig_dir>   (orig_dir holds index.html + assets/ fetched from the live app)"""
import re, sys, shutil, os
O=sys.argv[1]; P='/combat-le-rhume'; U='https://passcool17.github.io'+P
def rep(s,a,b,n=1):
    c=s.count(a); assert c==n,(a,c); return s.replace(a,b)
os.makedirs('assets',exist_ok=True)
for f in os.listdir(O+'/assets'): shutil.copy(O+'/assets/'+f,'assets/'+f)
f='assets/index-DQN6feKR.js'; s=open(f).read()
s=rep(s,'var pv=`/assets/styles','var pv=`'+P+'/assets/styles')
s=rep(s,'mv=`Remèdes Naturels`','mv=`Combat le rhume`')
s=rep(s,'href:`/favicon.svg`','href:`'+P+'/favicon.svg`')
s=rep(s,'href:`/__grok/manifest.webmanifest`','href:`'+P+'/manifest.webmanifest`')
s=rep(s,'href:`/__grok/icon-180.png`','href:`'+P+'/icons/apple-touch-icon.png`')
s=rep(s,'basepath:``,serializationAdapters','basepath:`'+P+'`,serializationAdapters')
s=rep(s,'_v=function(e){return`/`+e}','_v=function(e){return`'+P+'/`+e}')
# disable the Grok preview bridge (only used inside the Grok editor iframe)
s=rep(s,'function lv(){if(typeof window>`u`)return null;','function lv(){return null;if(typeof window>`u`)return null;')
open(f,'w').write(s)
f='assets/routes-BZb6ezsO.js'; s=open(f).read()
s=rep(s,'children:[`Remèdes `,(0,W.jsx)(`span`,{className:`italic text-primary`,children:`Naturels`})]','children:[`Combat le `,(0,W.jsx)(`span`,{className:`italic text-primary`,children:`rhume`})]')
open(f,'w').write(s)
h=open(O+'/index.html').read()
h=rep(h,'content="https://xenon-lark-charm-nova.grok.me/og.jpg"','content="'+U+'/og.jpg"')
h=rep(h,'<meta property="og:title" content="Remèdes Naturels">','<meta property="og:title" content="Combat le rhume"><meta property="og:description" content="Guide pratique pour le rhume et la grippe : protocole, plantes, préparations et suivi des symptômes."><meta property="og:url" content="'+U+'/"><meta property="og:type" content="website">')
h=rep(h,'<title>Remèdes Naturels</title>','<title>Combat le rhume</title>')
h=rep(h,'href="/assets/','href="'+P+'/assets/',3)
h=rep(h,'src="/assets/','src="'+P+'/assets/')
h=rep(h,'"/assets/','"'+P+'/assets/',3)  # TanStack dehydrated manifest
h=rep(h,'href="/favicon.svg"','href="'+P+'/favicon.svg"')
h=rep(h,'href="/__grok/manifest.webmanifest"','href="'+P+'/manifest.webmanifest"')
h=rep(h,'href="/__grok/icon-180.png"','href="'+P+'/icons/apple-touch-icon.png"')
h=rep(h,'content="Remèdes Naturels"','content="Combat le rhume"')
h=re.sub(r'<meta name="grok-project-id"[^>]*>','',h)
h=re.sub(r'<script src="https://grok\.com/[^>]*></script>','',h)
h=re.sub(r'<meta property="grok:app_id"[^>]*>','',h)
h=rep(h,'<p class="font-display text-lg leading-none text-ink">Remèdes <span class="italic text-primary">Naturels</span></p>','<p class="font-display text-lg leading-none text-ink">Combat le <span class="italic text-primary">rhume</span></p>')
h=rep(h,'<meta name="apple-mobile-web-app-status-bar-style"','<meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-status-bar-style"')
h=rep(h,'</body></html>','<script>if("serviceWorker"in navigator)addEventListener("load",function(){navigator.serviceWorker.register("'+P+'/sw.js",{scope:"'+P+'/"}).catch(function(){})});</script></body></html>')
m=re.search("grok|Naturels",h); assert not m, h[m.start()-150:m.end()+50] if m else ""
open('index.html','w').write(h)
print('patched')
